#include <iostream>
#include <clocale>
/*
Задание 2
Ввести базовую стоимость, количество страховых случаев за год и стаж. При двух и более случаях увеличить стоимость на 40%. 
Если случаев 0 и стаж не меньше 5 лет, после остальных расчётов дать скидку 10%. 
Если оба правила неприменимы, стоимость не менять. Отрицательные значения считать ошибкой.
*/
int main() {
    setlocale(LC_ALL, "Rus");

    double cost;
    int cases;
    int experience;

    std::cout << "Введите базовую стоимость: ";
    std::cin >> cost;
    std::cout << "Введите количество страховых случаев за год: ";
    std::cin >> cases;
    std::cout << "Введите стаж: ";
    std::cin >> experience;

    if (cost < 0  || cases < 0 || experience < 0) {
        std::cout << "Ошибка: значения не могут быть отрицательными\n";
        return -1;
    }

    if (cases >= 2) {
        cost = cost * 1.4;
        std::cout << "Надбавка 40% за два и более случая\n";
    }
    else if (cases == 0 && experience >= 5) {
        cost = cost * 0.9;
        std::cout << "Скидка 10% за безаварийность и стаж от 5 лет\n";
    }
    else {
        std::cout << "Правила не применены, стоимость не изменилась\n";
    }

    std::cout << "Итоговая стоимость: " << cost << "\n";

    return 0;
}